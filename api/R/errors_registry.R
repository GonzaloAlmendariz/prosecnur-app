# errors_registry.R — Registro central del vocabulario de errores E_* de la API.
#
# CONTRATO: código E_* nuevo ⇒ fila nueva en `errores_registrados()`, en el
# MISMO commit. El gate vive en tests/testthat/test-errors-registry.R: escanea
# api/R/*.R buscando literales E_* y se pone rojo si aparece un código sin
# registrar (o un huérfano registrado que ya no existe en el código).
#
# La tabla es DELIBERADAMENTE literal (hardcodeada, no un escaneo en runtime):
# es un contrato revisable en el diff, no un espejo automático del código.
#
# Alcance del censo (reglas explícitas):
# - Cuenta TODO string literal que calce con `^E_[A-Z0-9_]*[A-Z0-9]$` en el AST
#   de api/R/*.R, no solo llamadas directas a stop_api(). Así se capturan los
#   códigos que fluyen por wrappers de módulo (.acm_fail, .acb_error, .arx_stop,
#   .hf_fail, etc.) y los códigos de alertas embebidas en payloads (por ejemplo
#   las de hojas_ruta_engine.R).
# - Los códigos construidos dinámicamente quedan FUERA del gate. Patrón conocido:
#   paste0("E_PROCESSING_INTAKE_", toupper(reason$code)) en processing_intake.R.
#   La regla que los excluye es el `[A-Z0-9]$` final del regex: los prefijos de
#   construcción terminan en "_" y los códigos reales nunca.
# - errors_registry.R queda excluido del escaneo: contiene los literales del
#   registro y se censaría a sí mismo.
#
# Columnas de la tabla:
# - codigo: el código E_* literal.
# - modulo: archivo de api/R donde el código aparece más veces (origen principal;
#   desempate alfabético).
# - status: status HTTP observados en llamadas DIRECTAS a stop_api() con ese
#   código ("400,422" si varía por sitio); "dinamico" si el status es una
#   expresión; "indirecto" si el código solo fluye por wrappers/payloads y el
#   status no es observable estáticamente.

# Patrón de un código E_* real (los prefijos dinámicos terminan en "_", ver arriba).
.errores_codigo_regex <- "^E_[A-Z0-9_]*[A-Z0-9]$"

# Escáner AST compartido por el gate de testthat (y por el generador offline que
# produjo la tabla). Devuelve data.frame(codigo, archivo) con una fila por
# aparición literal en api/R. Se camina el AST parseado en vez de usar regex
# sobre texto para no confundir comentarios/multilínea con llamadas reales.
.errores_escanear_codigos <- function(dir_r) {
  archivos <- list.files(dir_r, pattern = "\\.R$", full.names = TRUE)
  # El registro se censaría a sí mismo: fuera del alcance (ver cabecera).
  archivos <- archivos[basename(archivos) != "errors_registry.R"]
  acumulado <- list()
  caminar <- function(e, archivo) {
    if (is.character(e)) {
      hit <- e[grepl(.errores_codigo_regex, e)]
      if (length(hit)) {
        acumulado[[length(acumulado) + 1L]] <<- data.frame(
          codigo = hit, archivo = archivo, stringsAsFactors = FALSE
        )
      }
      return(invisible())
    }
    if (is.call(e) || is.pairlist(e)) {
      lst <- as.list(e)
      for (i in seq_along(lst)) {
        # El símbolo vacío (argumento faltante, ej. x[, 1]) revienta al
        # evaluarse; single-bracket lo detecta sin forzar la evaluación.
        if (identical(lst[i], list(quote(expr = )))) next
        if (!is.null(lst[[i]])) caminar(lst[[i]], archivo)
      }
    }
    invisible()
  }
  for (path in archivos) {
    # Un archivo que no parsea rompe load_all() mucho antes que este censo; aquí
    # solo se salta para que el gate reporte códigos, no errores de sintaxis.
    exprs <- tryCatch(parse(path, keep.source = FALSE), error = function(e) NULL)
    if (is.null(exprs)) next
    for (ex in exprs) caminar(ex, basename(path))
  }
  if (!length(acumulado)) {
    return(data.frame(codigo = character(0), archivo = character(0), stringsAsFactors = FALSE))
  }
  do.call(rbind, acumulado)
}

