function construirIndiceDirecciones(contrato, { cubiertos, gobernadas }) {
  const destino = path.join(VAULT_SISTEMA, 'sistema', 'direcciones')
  const porModulo = new Map()
  for (const [clave, nodo] of contrato) {
    if (!porModulo.has(nodo.modulo)) porModulo.set(nodo.modulo, [])
    porModulo.get(nodo.modulo).push([clave, nodo])
  }

  const esperados = new Map()
  for (const [modulo, nodos] of porModulo) {
    const raiz = nodos.find(([, n]) => n.tipo === 'modulo')?.[1]
    const filas = nodos.map(([clave, nodo]) => {
      const docs = (gobernadas.get(clave) ?? []).map((rel) => {
        const desde = path.join(destino, 'x')
        return `[${path.basename(rel, '.md')}](${path.relative(path.dirname(desde), path.join(REPO, rel)).split(path.sep).join('/')})`
      })
      return `| \`${clave}\` | ${nodo.tipo} | ${nodo.label ?? '—'} | ${nodo.direccionPublicada ? 'sí' : 'no; usa \`nodo:\`'} | ${nodo.sello} | ${cubiertos.has(clave) ? 'sí' : '**no**'} | ${docs.join(', ') || '—'} |`
    })

    const cuerpo = [
      `<!-- ${GENERATED} -->`,
      '',
      `# Direcciones de ${raiz?.label ?? modulo}`,
      '',
      '> Documento generado por `scripts/vaults-check.mjs --generar`. No editar a mano:',
      '> la fuente es `frontend/src/lib/modules.ts` más las secciones `## Gobierna`',
      '> de la bóveda de sistema.',
      '',
      `Módulo \`${modulo}\`${raiz?.to ? ` · ruta \`${raiz.to}\`` : ''} · ${nodos.length} direcciones.`,
      '',
      '| Dirección | Tipo | Nombre visible | URL publicada | Sello | Documentada | Gobernada por |',
      '| --- | --- | --- | --- | --- | --- | --- |',
      ...filas,
      '',
    ].join('\n')

    esperados.set(path.join(destino, `${modulo}.md`), cuerpo)
  }

  const indice = [
    `<!-- ${GENERATED} -->`,
    '',
    '# Índice de direcciones',
    '',
    '> Documento generado por `scripts/vaults-check.mjs --generar`. No editar a mano.',
    '',
    'Cada dirección del contrato de navegación, con el documento que la gobierna',
    'y si la bóveda de producto la documenta. Es la costura entre las dos bóvedas:',
    'la de producto explica qué hace una pantalla, la de sistema por qué existe.',
    '',
    ...[...porModulo.keys()].map((m) => `- [${m}](${m}.md)`),
    '',
  ].join('\n')
  esperados.set(path.join(destino, 'README.md'), indice)
  return { destino, esperados }
}

function archivosMarkdownDirectos(dir) {
  if (!fs.existsSync(dir)) return []
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((entrada) => entrada.isFile() && entrada.name.endsWith('.md'))
    .map((entrada) => path.join(dir, entrada.name))
}

function esIndiceGenerado(archivo) {
  if (!fs.existsSync(archivo)) return false
  const texto = fs.readFileSync(archivo, 'utf8')
  return texto.startsWith(`<!-- ${GENERATED} -->\n`)
}

function validarIndiceDirecciones(indice, resultado) {
  const push = (sujeto, detalle) => resultado.hallazgos.push({ codigo: 'G1', gravedad: 'bloqueante', sujeto, detalle })
  for (const [archivo, esperado] of indice.esperados) {
    const rel = path.relative(REPO, archivo)
    if (!fs.existsSync(archivo)) push(rel, 'adaptador generado ausente; ejecuta `make vaults-index`')
    else if (fs.readFileSync(archivo, 'utf8') !== esperado) push(rel, 'adaptador generado desactualizado; ejecuta `make vaults-index`')
  }
  for (const archivo of archivosMarkdownDirectos(indice.destino)) {
    if (!indice.esperados.has(archivo)) push(path.relative(REPO, archivo), 'archivo extra dentro del directorio generado')
  }
}

function escrituraAtomica(archivo, contenido) {
  fs.mkdirSync(path.dirname(archivo), { recursive: true })
  const temporal = path.join(path.dirname(archivo), `.${path.basename(archivo)}.${process.pid}.${crypto.randomUUID()}.tmp`)
  try {
    fs.writeFileSync(temporal, contenido, 'utf8')
    fs.renameSync(temporal, archivo)
  } finally {
    if (fs.existsSync(temporal)) fs.unlinkSync(temporal)
  }
}

function generarIndiceDirecciones(indice) {
  for (const [archivo, contenido] of indice.esperados) {
    if (fs.existsSync(archivo) && fs.readFileSync(archivo, 'utf8') === contenido) continue
    if (fs.existsSync(archivo) && !esIndiceGenerado(archivo)) {
      throw new Error(`${path.relative(REPO, archivo)} colisiona con un archivo manual; se preservó`)
    }
    escrituraAtomica(archivo, contenido)
  }
  for (const archivo of archivosMarkdownDirectos(indice.destino)) {
    if (indice.esperados.has(archivo)) continue
    if (!esIndiceGenerado(archivo)) throw new Error(`${path.relative(REPO, archivo)} es manual; no se puede podar`)
    fs.unlinkSync(archivo)
  }
  return [...indice.esperados.keys()].map((archivo) => path.relative(REPO, archivo))
}

