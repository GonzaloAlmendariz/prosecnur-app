function rel(filePath) {
  return path.relative(repoRoot, filePath) || '.'
}

function absolute(repoPath) {
  return path.resolve(repoRoot, repoPath)
}

function fail(message) {
  errors.push(message)
}

function readJson(filePath, label) {
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'))
  } catch (error) {
    fail(`${label}: ${error.message}`)
    return null
  }
}

function parseFrontmatter(filePath) {
  const content = fs.readFileSync(filePath, 'utf8')
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/)
  if (!match) throw new Error(`${rel(filePath)} no tiene frontmatter YAML válido`)

  const values = {}
  for (const line of match[1].split(/\r?\n/)) {
    if (!line.trim() || /^\s/.test(line)) continue
    const separator = line.indexOf(':')
    if (separator < 0) continue
    const key = line.slice(0, separator).trim()
    let value = line.slice(separator + 1).trim()
    if (value.startsWith('"') && value.endsWith('"')) value = JSON.parse(value)
    if (value === 'true') value = true
    if (value === 'false') value = false
    values[key] = value
  }
  return values
}

function csv(value) {
  if (Array.isArray(value)) return value
  if (typeof value !== 'string') return []
  return value.split(',').map((item) => item.trim()).filter(Boolean)
}

function listCanonicalNames(baseDir, kind) {
  const dir = absolute(baseDir)
  if (!fs.existsSync(dir)) {
    fail(`${baseDir} no existe`)
    return []
  }
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((entry) => kind === 'skill'
      ? entry.isDirectory() && fs.existsSync(path.join(dir, entry.name, 'SKILL.md'))
      : entry.isFile() && entry.name.endsWith('.md'))
    .map((entry) => kind === 'skill' ? entry.name : entry.name.slice(0, -3))
    .sort()
}

function compareInventory(label, expected, actual) {
  const missing = expected.filter((name) => !actual.includes(name))
  const extra = actual.filter((name) => !expected.includes(name))
  if (missing.length) fail(`${label}: faltan en fuente canónica: ${missing.join(', ')}`)
  if (extra.length) fail(`${label}: faltan en manifest.json: ${extra.join(', ')}`)
}

function ensureArray(value, label) {
  if (!Array.isArray(value)) {
    fail(`${label} debe ser un array`)
    return []
  }
  return value
}

function ensureInsideRepo(filePath) {
  const relative = path.relative(repoRoot, filePath)
  if (relative.startsWith('..') || path.isAbsolute(relative)) {
    throw new Error(`salida fuera del repositorio: ${filePath}`)
  }
  for (const protectedPath of PROTECTED_PATHS) {
    const protectedAbsolute = absolute(protectedPath)
    if (filePath === protectedAbsolute || filePath.startsWith(`${protectedAbsolute}${path.sep}`)) {
      throw new Error(`salida invade fuente canónica protegida: ${rel(filePath)}`)
    }
  }
}

function assertNoSymlink(filePath) {
  ensureInsideRepo(filePath)
  const relative = path.relative(repoRoot, filePath)
  let current = repoRoot
  for (const segment of relative.split(path.sep).filter(Boolean)) {
    current = path.join(current, segment)
    try {
      if (fs.lstatSync(current).isSymbolicLink()) {
        throw new Error(`ruta de adaptador contiene symlink: ${rel(current)}`)
      }
    } catch (error) {
      if (error.code === 'ENOENT') break
      throw error
    }
  }
}

function validateAdapterRoots() {
  for (const [key, expected] of Object.entries(ADAPTER_PATHS)) {
    if (manifest.adapters[key] !== expected) fail(`adapters.${key} debe ser ${expected}`)
    try {
      assertNoSymlink(absolute(expected))
    } catch (error) {
      fail(error.message)
    }
  }
}

