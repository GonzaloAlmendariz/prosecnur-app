#!/usr/bin/env node

import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(scriptDir, '..')
const manifestPath = path.join(scriptDir, 'manifest.json')
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
const args = new Set(process.argv.slice(2))
const writeMode = args.has('--write')
const checkMode = args.has('--check') || !writeMode
const allowedArgs = new Set(['--check', '--write'])
const unknownArgs = [...args].filter((arg) => !allowedArgs.has(arg))

if (unknownArgs.length > 0) {
  console.error(`Argumentos desconocidos: ${unknownArgs.join(', ')}`)
  process.exit(2)
}

const errors = []
const warnings = []

function rel(filePath) {
  return path.relative(repoRoot, filePath) || '.'
}

function parseFrontmatter(filePath) {
  const content = fs.readFileSync(filePath, 'utf8')
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/)
  if (!match) throw new Error(`${rel(filePath)} no tiene frontmatter YAML válido`)

  const values = {}
  for (const line of match[1].split(/\r?\n/)) {
    const separator = line.indexOf(':')
    if (separator < 0) continue
    const key = line.slice(0, separator).trim()
    let value = line.slice(separator + 1).trim()
    if (value.startsWith('"') && value.endsWith('"')) {
      value = JSON.parse(value)
    }
    values[key] = value
  }

  if (!values.name || !values.description) {
    throw new Error(`${rel(filePath)} debe declarar name y description`)
  }
  return values
}

function expectedSkillAdapter(name, description) {
  const canonical = `../../../${manifest.canonical.skills_dir}/${name}/SKILL.md`
  return `---\nname: ${JSON.stringify(name)}\ndescription: ${JSON.stringify(description)}\n---\n\n<!-- GENERATED BY agentic/sync-agentic-os.mjs; DO NOT EDIT -->\n\n# Adaptador Codex\n\nAntes de actuar, lee completamente \`${canonical}\` y sigue esa fuente canónica.\n\n- Resuelve la ruta desde este directorio de skill.\n- Si la fuente canónica no existe o no puede leerse, detente y reporta el bloqueo.\n- Para mejorar el skill, edita la fuente en \`${manifest.canonical.skills_dir}/${name}/SKILL.md\` y luego ejecuta \`node agentic/sync-agentic-os.mjs --write\`.\n- No dupliques ni reemplaces las instrucciones canónicas dentro de este adaptador.\n`
}

function expectedAgentAdapter(name, description) {
  const source = `${manifest.canonical.agents_dir}/${name}.md`
  const instructions = [
    'Antes de actuar, localiza la raiz del repositorio y lee completamente AGENTS.md, CLAUDE.md y ' + source + '.',
    'Sigue el archivo Markdown canonico como instrucciones especializadas de este agente.',
    'Preserva cambios ajenos y respeta Loops de reparacion.',
    'Si el archivo canonico no existe o no puede leerse, detente y reporta el bloqueo.',
    'No edites este adaptador TOML; las mejoras se hacen en ' + source + ' y se sincronizan con node agentic/sync-agentic-os.mjs --write.'
  ].join('\n')

  return `# GENERATED BY agentic/sync-agentic-os.mjs; DO NOT EDIT\nname = ${JSON.stringify(name)}\ndescription = ${JSON.stringify(description)}\ndeveloper_instructions = ${JSON.stringify(instructions)}\n`
}

function compareOrWrite(filePath, expected) {
  if (writeMode) {
    fs.mkdirSync(path.dirname(filePath), { recursive: true })
    fs.writeFileSync(filePath, expected, 'utf8')
  }
  if (!fs.existsSync(filePath)) {
    errors.push(`${rel(filePath)} no existe`)
    return
  }
  const actual = fs.readFileSync(filePath, 'utf8')
  if (actual !== expected) errors.push(`${rel(filePath)} está desincronizado`)
}

function listCanonicalNames(baseDir, suffix) {
  const absolute = path.join(repoRoot, baseDir)
  return fs.readdirSync(absolute, { withFileTypes: true })
    .filter((entry) => suffix === '/SKILL.md' ? entry.isDirectory() : entry.isFile() && entry.name.endsWith(suffix))
    .map((entry) => suffix === '/SKILL.md' ? entry.name : entry.name.slice(0, -suffix.length))
    .sort()
}

function compareInventory(kind, expected, actual) {
  const missing = expected.filter((name) => !actual.includes(name))
  const extra = actual.filter((name) => !expected.includes(name))
  if (missing.length) errors.push(`${kind}: faltan en fuente canónica: ${missing.join(', ')}`)
  if (extra.length) errors.push(`${kind}: faltan en manifest.json: ${extra.join(', ')}`)
}

compareInventory('skills', manifest.skills, listCanonicalNames(manifest.canonical.skills_dir, '/SKILL.md'))
compareInventory('agents', manifest.agents, listCanonicalNames(manifest.canonical.agents_dir, '.md'))

const codexConfigPath = path.join(repoRoot, manifest.adapters.codex_config)
if (!fs.existsSync(codexConfigPath)) {
  errors.push(`${rel(codexConfigPath)} no existe`)
} else {
  const codexConfig = fs.readFileSync(codexConfigPath, 'utf8')
  if (!/^\[agents\]$/m.test(codexConfig)) errors.push(`${rel(codexConfigPath)} no declara [agents]`)
  if (!/^max_threads\s*=\s*4$/m.test(codexConfig)) errors.push(`${rel(codexConfigPath)} debe limitar max_threads a 4`)
  if (!/^max_depth\s*=\s*1$/m.test(codexConfig)) errors.push(`${rel(codexConfigPath)} debe limitar max_depth a 1`)
}

for (const name of manifest.skills) {
  const source = path.join(repoRoot, manifest.canonical.skills_dir, name, 'SKILL.md')
  try {
    const metadata = parseFrontmatter(source)
    if (metadata.name !== name) errors.push(`${rel(source)} declara name=${metadata.name}, esperaba ${name}`)
    const adapter = path.join(repoRoot, manifest.adapters.codex_skills_dir, name, 'SKILL.md')
    compareOrWrite(adapter, expectedSkillAdapter(name, metadata.description))
  } catch (error) {
    errors.push(error.message)
  }
}

for (const name of manifest.agents) {
  const source = path.join(repoRoot, manifest.canonical.agents_dir, `${name}.md`)
  try {
    const metadata = parseFrontmatter(source)
    if (metadata.name !== name) errors.push(`${rel(source)} declara name=${metadata.name}, esperaba ${name}`)
    const adapter = path.join(repoRoot, manifest.adapters.codex_agents_dir, `${name}.toml`)
    compareOrWrite(adapter, expectedAgentAdapter(name, metadata.description))
  } catch (error) {
    errors.push(error.message)
  }
}

for (const name of manifest.external_skills) {
  const candidates = [
    path.join(os.homedir(), '.claude', 'skills', name, 'SKILL.md'),
    path.join(os.homedir(), '.agents', 'skills', name, 'SKILL.md'),
    path.join(os.homedir(), '.codex', 'skills', name, 'SKILL.md')
  ]
  if (!candidates.some((candidate) => fs.existsSync(candidate))) {
    warnings.push(`skill externo no disponible en esta máquina: ${name}`)
  }
}

if (warnings.length) {
  for (const warning of warnings) console.warn(`WARN: ${warning}`)
}

if (errors.length) {
  for (const error of errors) console.error(`ERROR: ${error}`)
  process.exit(1)
}

const verb = writeMode ? 'generados y verificados' : 'verificados'
console.log(`OK: ${manifest.skills.length} skills y ${manifest.agents.length} agentes ${verb}; fuentes canónicas de Claude intactas.`)
if (checkMode && writeMode) console.log('Nota: --write también ejecutó la comprobación final.')
